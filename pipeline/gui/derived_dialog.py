    # ---- helpers
    def _base_df(self):
        """Current file's (compensated) events WITHOUT the saved derived
        columns — the preview re-applies the work list on top of that."""
        df = self.app._get_data(self.app.current_path).df
        return df.drop(columns=[p.name for p in self.app.derived_params], errors="ignore")

    def _file_channels(self) -> list[str]:
        return list(self._base_df().columns)

    def _fill_channel_list(self):
        markers = self.app._get_data(self.app.current_path).marker_names or {}
        self.chan_list.delete(0, "end")
        self._chan_names = self._file_channels() + [p.name for p in self.work[: self.index or 0]]
        for ch in self._chan_names:
            label = f"{ch}   ({markers[ch]})" if ch in markers else ch
            if self._derived_name(ch):
                label = f"{ch}   (abgeleitet)"
            self.chan_list.insert("end", label)

    def _derived_name(self, name: str) -> bool:
        return any(p.name == name for p in self.work)

    def _refresh_list(self):
        self.listbox.delete(0, "end")
        for p in self.work:
            self.listbox.insert("end", p.name)
        if self.index is not None:
            self.listbox.selection_set(self.index)

    def _insert(self, text: str):
        self.formula_text.insert("insert", text)
        self.formula_text.focus_set()

    def _insert_channel(self, _event=None):
        sel = self.chan_list.curselection()
        if sel:
            self._insert(f"[{self._chan_names[sel[0]]}]")

    def _formula(self) -> str:
        return self.formula_text.get("1.0", "end").strip()

    def _set_text(self, widget: tk.Text, text: str):
        widget.delete("1.0", "end")
        widget.insert("1.0", text)
        widget.edit_modified(False)

    def _parse_constants(self) -> tuple[dict[str, float], str | None]:
        consts: dict[str, float] = {}
        for i, line in enumerate(self.const_text.get("1.0", "end").splitlines(), start=1):
            line = line.split("#")[0].strip()
            if not line:
                continue
            if "=" not in line:
                return consts, f"Konstanten Zeile {i}: bitte 'Name = Wert' schreiben."
            name, value = (s.strip() for s in line.split("=", 1))
            if not valid_constant_name(name):
                return consts, f"Konstanten Zeile {i}: '{name}' ist kein gültiger Name (Buchstaben, Ziffern, _)."
            try:
                consts[name] = float(value.replace(",", "."))
            except ValueError:
                return consts, f"Konstanten Zeile {i}: '{value}' ist keine Zahl."
        return consts, None

    def _constants_to_text(self, consts: dict[str, float]) -> str:
        return "\n".join(f"{k} = {v:g}" for k, v in consts.items())

    def _parse_axis(self) -> tuple[float | None, float | None, str | None]:
        out = []
        for label, var in (("Min", self.axis_min_var), ("Max", self.axis_max_var)):
            s = var.get().strip().replace(",", ".")
            if not s:
                out.append(None)
                continue
            try:
                out.append(float(s))
            except ValueError:
                return None, None, f"Achsen-{label} '{s}' ist keine Zahl."
        if out[0] is not None and out[1] is not None and out[1] <= out[0]:
            return None, None, "Achsen-Max muss größer als Min sein."
        return out[0], out[1], None

    def _editor_param(self) -> tuple[DerivedParam | None, str | None]:
        consts, err = self._parse_constants()
        if err:
            return None, err
        lo, hi, err = self._parse_axis()
        if err:
            return None, err
        return DerivedParam(self.name_var.get().strip(), self._formula(), consts, lo, hi), None

    # ---- editing
    def _on_formula_modified(self, _e=None):
        if self.formula_text.edit_modified():
            self.formula_text.edit_modified(False)
            self._on_edit()

    def _on_const_modified(self, _e=None):
        if self.const_text.edit_modified():
            self.const_text.edit_modified(False)
            self._on_edit()

    def _on_edit(self):
        if self._loading or self.index is None:
            return
        param, _err = self._editor_param()
        if param is not None:  # keep the work list in sync (name shown live in the list)
            self.work[self.index] = param
            if self.listbox.get(self.index) != param.name:
                self.listbox.delete(self.index)
                self.listbox.insert(self.index, param.name)
                self.listbox.selection_set(self.index)
        self._schedule_preview()

    def _load_editor(self, p: DerivedParam):
        self._loading = True
        self.name_var.set(p.name)
        self._set_text(self.formula_text, p.formula)
        self._set_text(self.const_text, self._constants_to_text(p.constants))
        self.axis_min_var.set("" if p.axis_min is None else f"{p.axis_min:g}")
        self.axis_max_var.set("" if p.axis_max is None else f"{p.axis_max:g}")
        self._loading = False
        self._fill_channel_list()
        self._schedule_preview()

    def _select(self, i: int):
        self.index = i
        self._refresh_list()
        self._load_editor(self.work[i])

    def _on_list_select(self, _e=None):
        sel = self.listbox.curselection()
        if not sel or sel[0] == self.index:
            return
        err = self._check_current()
        if err:
            messagebox.showwarning("Bitte korrigieren", err, parent=self.win)
            self._refresh_list()
            return
        self._select(sel[0])

    def _unique_name(self, base: str) -> str:
        """base, or 'base 2', 'base 3', ... — not clashing with a channel or
        another parameter (the one being edited doesn't count)."""
        names = {p.name for i, p in enumerate(self.work) if i != self.index} | set(self._file_channels())
        name, n = base, 2
        while name in names:
            name, n = f"{base} {n}", n + 1
        return name

    def _new(self):
        if self.index is not None and (err := self._check_current()):
            messagebox.showwarning("Bitte korrigieren", err, parent=self.win)
            return
        self.index = None
        name = self._unique_name("Neu")
        self._auto_names.add(name)
        self.work.append(DerivedParam(name, ""))
        self._select(len(self.work) - 1)

    def _duplicate(self):
        if self.index is None:
            return
        p = copy.deepcopy(self.work[self.index])
        p.name = self._unique_name(p.name)
        self.work.insert(self.index + 1, p)
        self._select(self.index + 1)

    def _delete(self):
        if self.index is None:
            return
        name = self.work[self.index].name
        if not messagebox.askyesno("Löschen", f"Parameter '{name}' löschen?", parent=self.win):
            return
        del self.work[self.index]
        self.index = None
        if self.work:
            self._select(0)
        else:
            self._new()

    def _apply_template(self):
        a, b = self.tpl_a_var.get(), self.tpl_b_var.get()
        if not a or not b:
            messagebox.showinfo("Kanäle wählen", "Bitte Kanal A und B für die Vorlage wählen.", parent=self.win)
            return
        name, formula, consts, (lo, hi) = fill_template(self.tpl_var.get(), a, b)
        self._loading = True
        current = self.name_var.get().strip()
        if not current or current in self._auto_names:  # never overwrite a name the user typed
            name = self._unique_name(name)
            self._auto_names.add(name)
            self.name_var.set(name)
        self._set_text(self.formula_text, formula)
        self._set_text(self.const_text, self._constants_to_text(consts))
        self.axis_min_var.set("" if lo is None else f"{lo:g}")
        self.axis_max_var.set("" if hi is None else f"{hi:g}")
        self._loading = False
        self._on_edit()

    def _add_missing_constants(self):
        try:
            used = used_constant_names(self._formula())
        except FormulaError as exc:
            messagebox.showwarning("Formel fehlerhaft", str(exc), parent=self.win)
            return
        consts, err = self._parse_constants()
        if err:
            messagebox.showwarning("Konstanten", err, parent=self.win)
            return
        missing = sorted(n for n in used if n not in consts)
        if not missing:
            return
        for n in missing:
            consts[n] = 1.0 if n.upper().startswith("G") else 0.0
        self._set_text(self.const_text, self._constants_to_text(consts))
        self._on_edit()

    def _measure_constant(self):
        """Median/mean of a channel in the current file, population = what the
        Gating tab currently shows — e.g. the autofluorescence of the
        unstained control."""
        app = self.app
        fcs = app._get_data(app.current_path)
        mask = app._cumulative_pending_mask(fcs.df)
        pop = app.gate_tree[app.current_node_id].name
        consts, _ = self._parse_constants()
        try:
            names = sorted(used_constant_names(self._formula()) | set(consts))
        except FormulaError:
            names = sorted(consts)

        dlg = tk.Toplevel(self.win)
        dlg.title("Wert messen")
        dlg.transient(self.win)
        ttk.Label(dlg, text=f"Datei: {fcs.filename}\nPopulation: {pop}  ({int(mask.sum())} Events)",
                  justify="left").grid(row=0, column=0, columnspan=2, sticky="w", padx=8, pady=8)
        ttk.Label(dlg, text="Konstante:").grid(row=1, column=0, sticky="w", padx=8)
        const_var = tk.StringVar(value=next((n for n in names if n.upper().startswith("AF")), names[0] if names else ""))
        ttk.Combobox(dlg, textvariable=const_var, values=names, width=20).grid(row=1, column=1, padx=8, pady=2)
        ttk.Label(dlg, text="Kanal:").grid(row=2, column=0, sticky="w", padx=8)
        chans = self._file_channels()
        chan_var = tk.StringVar(value=self.tpl_a_var.get() if self.tpl_a_var.get() in chans else chans[0])
        ttk.Combobox(dlg, textvariable=chan_var, values=chans, state="readonly", width=20).grid(
            row=2, column=1, padx=8, pady=2)
        ttk.Label(dlg, text="Statistik:").grid(row=3, column=0, sticky="w", padx=8)
        stat_var = tk.StringVar(value="Median")
        ttk.Combobox(dlg, textvariable=stat_var, values=["Median", "Mittelwert"], state="readonly", width=20).grid(
            row=3, column=1, padx=8, pady=2)
        result_var = tk.StringVar()
        ttk.Label(dlg, textvariable=result_var, foreground="#1f4e8c").grid(row=4, column=0, columnspan=2, padx=8)

        def value():
            vals = fcs.df[chan_var.get()].to_numpy(dtype=float)[mask]
            vals = vals[np.isfinite(vals)]
            if not len(vals):
                return None
            return float(np.median(vals) if stat_var.get() == "Median" else np.mean(vals))

        def update(*_):
            v = value()
            result_var.set("keine Events" if v is None else f"= {v:.6g}")

        def take():
            name = const_var.get().strip()
            if not valid_constant_name(name):
                messagebox.showwarning("Name", "Bitte einen gültigen Konstanten-Namen (z.B. AF_A) eingeben.", parent=dlg)
                return
            v = value()
            if v is None:
                return
            c, err = self._parse_constants()
            if err:
                messagebox.showwarning("Konstanten", err, parent=dlg)
                return
            c[name] = round(v, 6)
            self._set_text(self.const_text, self._constants_to_text(c))
            self._on_edit()
            dlg.destroy()

        chan_var.trace_add("write", update)
        stat_var.trace_add("write", update)
        update()
        row = ttk.Frame(dlg)
        row.grid(row=5, column=0, columnspan=2, sticky="e", padx=8, pady=8)
        ttk.Button(row, text="Abbrechen", command=dlg.destroy).pack(side="right", padx=2)
        ttk.Button(row, text="Übernehmen", command=take).pack(side="right", padx=2)
        dlg.grab_set()

    # ---- validation / preview
    def _check_current(self) -> str | None:
        """Error message if the edited parameter can't be used, else None."""
        if self.index is None:
            return None
        param, err = self._editor_param()
        if err:
            return err
        if not param.formula:
            return None  # empty draft: allowed, dropped on save
        others = [p.name for i, p in enumerate(self.work) if i != self.index]
        err = validate_name(param.name, others, self._file_channels())
        if err:
            return err
        try:
            base, _ = apply_derived(self._base_df(), self.work[: self.index],
                                    self.app._get_data(self.app.current_path).marker_names)
            evaluate(param, base.head(50), self.app._get_data(self.app.current_path).marker_names)
        except FormulaError as exc:
            return f"'{param.name}': {exc}"
        self.work[self.index] = param
        return None

    def _schedule_preview(self):
        if self._preview_job is not None:
            self.win.after_cancel(self._preview_job)
        self._preview_job = self.win.after(300, self._update_preview)

    def _update_preview(self):
        self._preview_job = None
        if not self.win.winfo_exists() or self.index is None:
            return
        self.prev_ax.clear()
        app = self.app
        param, err = self._editor_param()
        if param is not None and not param.formula:
            err = "Formel eingeben — oder oben eine Vorlage übernehmen."
        if param is not None and not err:
            err = validate_name(param.name, [p.name for i, p in enumerate(self.work) if i != self.index],
                                self._file_channels())
        values = None
        if not err:
            try:
                fcs = app._get_data(app.current_path)
                base, _ = apply_derived(self._base_df(), self.work[: self.index], fcs.marker_names)
                values = evaluate(param, base, fcs.marker_names)
                mask = app._cumulative_pending_mask(fcs.df)
            except FormulaError as exc:
                err = str(exc)
            except Exception as exc:
                err = f"{type(exc).__name__}: {exc}"
        if err:
            self.preview_label.configure(foreground="#b00020")
            self.preview_var.set(err)
            self.prev_canvas.draw_idle()
            return

        pop = app.gate_tree[app.current_node_id].name
        v = values[mask]
        valid = v[np.isfinite(v)]
        lines = [f"{os.path.basename(app.current_path)}", f"Population '{pop}': {len(v)} Events"]
        if len(valid):
            p5, med, p95 = np.percentile(valid, [5, 50, 95])
            lines += [f"Median: {med:.4g}    Mittelwert: {np.mean(valid):.4g}", f"5–95 %: {p5:.4g} … {p95:.4g}"]
        n_bad = len(v) - len(valid)
        if n_bad:
            lines.append(f"ungültig (÷0, log<0 …): {n_bad} ({100.0 * n_bad / max(len(v), 1):.1f} %)")
        self.preview_label.configure(foreground="")
        self.preview_var.set("\n".join(lines))
        if len(valid):
            lo, hi = param.axis_min, param.axis_max
            if lo is None or hi is None:
                p_lo, p_hi = np.percentile(valid, [0.5, 99.5])
                lo = p_lo if lo is None else lo
                hi = p_hi if hi is None else hi
            if hi <= lo:
                hi = lo + 1.0
            self.prev_ax.hist(np.clip(valid, lo, hi), bins=120, range=(lo, hi), color="#1f4e8c")
            self.prev_ax.set_xlim(lo, hi)
        self.prev_ax.tick_params(labelsize=7)
        self.prev_ax.set_yticks([])
        self.prev_fig.tight_layout()
        self.prev_canvas.draw_idle()

    # ---- save / close
    def _save(self):
        err = self._check_current()
        if err:
            messagebox.showwarning("Bitte korrigieren", err, parent=self.win)
            return
        # drop never-filled entries silently (e.g. the empty one created on open)
        self.work = [p for p in self.work if p.formula.strip()]
        names = [p.name for p in self.work]
        if len(set(names)) != len(names):
            messagebox.showwarning("Doppelte Namen", "Zwei Parameter haben denselben Namen.", parent=self.win)
            return
        app = self.app
        try:
            save_derived(app.input_dir, self.work)
        except OSError as exc:
            messagebox.showwarning(
                "Nicht gespeichert",
                f"Konnte die Formeln nicht im Experiment-Ordner speichern ({exc}).\nSie gelten nur für diese Sitzung.",
                parent=self.win,
            )
        app.derived_params = self.work
        app._update_derived_button()
        self._close()
        app._invalidate_compensated_data()
        app.status_var.set(
            f"{len(self.work)} abgeleitete(r) Parameter aktiv: {', '.join(names) or '—'} "
            f"(als Kanäle in allen Tabs wählbar)."
        )

    def _close(self):
        if self._preview_job is not None:
            self.win.after_cancel(self._preview_job)
        self.app._derived_win = None
        self.win.destroy()
