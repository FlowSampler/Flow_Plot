class DerivedParamsMixin:
    """'Abgeleitete Parameter': formulas evaluated per event, added as extra
    channels to every file (stored in '<experiment>/derived_parameters.json')."""

    def _load_derived_params(self):
        self.derived_params: list[DerivedParam] = load_derived(self.input_dir) if self.input_dir else []
        self._update_derived_button()

    def _derived_param(self, name: str) -> DerivedParam | None:
        return next((p for p in getattr(self, "derived_params", []) if p.name == name), None)

    def _update_derived_button(self):
        if hasattr(self, "derived_button"):
            n = len(self.derived_params)
            self.derived_button.configure(text=f"Abgeleitete Parameter / Formeln ({n})..." if n
                                          else "Abgeleitete Parameter / Formeln...")

    # ---- dialog --------------------------------------------------------------
    def _open_derived_dialog(self):
        if not self.current_path:
            messagebox.showinfo("Keine Datei", "Bitte zuerst einen Experiment-Ordner mit .fcs-Dateien laden.")
            return
        existing = getattr(self, "_derived_win", None)
        if existing is not None and existing.winfo_exists():
            existing.lift()
            return
        _DerivedDialog(self)


